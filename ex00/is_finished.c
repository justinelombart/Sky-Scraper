int	is_finished(int **map)
{
	int	i;
	int	j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			if (!map[i][j])
				return (0);
			j++;
		}
		i++;
	}
	return (1);
}
