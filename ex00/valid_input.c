int	valid_input(char *str)
{
	int	i;

	i = 0;
	while (str[i])
	{
		if (i > 30)
			return (0);
		if (!(i % 2) && (str[i] < '1' || str[i] > '4'))
			return (0);
		else if ((i % 2) && (str[i] != ' '))
			return (0);
		i++;
	}
	if (i != 31)
		return (0);
	return (1);
}
